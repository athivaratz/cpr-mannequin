#!/usr/bin/env python3
"""Gzip the dashboard files into a PROGMEM header for the ESP32 firmware.

Runs as a PlatformIO ``pre:`` extra script and also works on its own:

    python3 tools/embed_web.py
"""

import gzip
import io
import os

MIME_TYPES = {
    ".html": "text/html; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".woff2": "font/woff2",
    ".json": "application/json",
    ".jsonl": "application/x-ndjson",
    ".svg": "image/svg+xml",
    ".ico": "image/x-icon",
    ".txt": "text/plain; charset=utf-8",
}

SKIP_NAMES = {".gitkeep", ".DS_Store"}


def _project_dir():
    env = _scons_env()
    if env is not None:
        return env.subst("$PROJECT_DIR")
    return os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def _scons_env():
    try:
        Import("env")  # noqa: F821  (provided by SCons)
        return env  # noqa: F821
    except Exception:
        return None


def _gzip_bytes(data):
    out = io.BytesIO()
    with gzip.GzipFile(filename="", mode="wb", fileobj=out,
                       compresslevel=9, mtime=0) as handle:
        handle.write(data)
    return out.getvalue()


def _mime_for(rel_path):
    ext = os.path.splitext(rel_path)[1].lower()
    return MIME_TYPES.get(ext, "application/octet-stream")


def _collect_files(web_dir):
    found = []
    for dirpath, dirnames, filenames in os.walk(web_dir):
        dirnames.sort()
        for name in sorted(filenames):
            if name in SKIP_NAMES:
                continue
            full = os.path.join(dirpath, name)
            if not os.path.isfile(full):
                continue
            rel = os.path.relpath(full, web_dir).replace(os.sep, "/")
            with open(full, "rb") as handle:
                raw = handle.read()
            found.append({
                "path": "/" + rel,
                "mime": _mime_for(rel),
                "raw_size": len(raw),
                "gz": _gzip_bytes(raw),
            })
    found.sort(key=lambda item: item["path"])
    return found


def _c_array(name, data):
    if not data:
        return [
            "static const uint8_t %s[] PROGMEM = { 0x00 };" % name,
        ]

    lines = ["static const uint8_t %s[] PROGMEM = {" % name]
    per_line = 16
    for offset in range(0, len(data), per_line):
        chunk = data[offset:offset + per_line]
        values = ", ".join("0x%02X" % byte for byte in chunk)
        comma = "," if offset + per_line < len(data) else ""
        lines.append("  %s%s" % (values, comma))
    lines.append("};")
    return lines


def _build_header(files):
    lines = [
        "// Generated by tools/embed_web.py. Do not edit.",
        "#ifndef CPR_WEB_ASSETS_H",
        "#define CPR_WEB_ASSETS_H",
        "",
        "#include <Arduino.h>",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "struct WebAsset {",
        "  const char* path;",
        "  const char* mime;",
        "  const uint8_t* data;",
        "  size_t len;",
        "};",
        "",
    ]

    for index, item in enumerate(files):
        lines.extend(_c_array("kAsset%d" % index, item["gz"]))
        lines.append("")

    lines.append("static const WebAsset kWebAssets[] = {")
    for index, item in enumerate(files):
        lines.append(
            '  {"%s", "%s", kAsset%d, %d},'
            % (item["path"], item["mime"], index, len(item["gz"]))
        )
    lines.append("};")
    lines.append("")
    lines.append("static const size_t kWebAssetCount = "
                 "sizeof(kWebAssets) / sizeof(kWebAssets[0]);")
    lines.append("")
    lines.append("#endif  // CPR_WEB_ASSETS_H")
    lines.append("")
    return "\n".join(lines)


def _write_if_changed(path, text):
    try:
        with open(path, "r", encoding="utf-8") as handle:
            if handle.read() == text:
                return
    except OSError:
        pass
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


def main():
    root = _project_dir()
    web_dir = os.path.join(root, "web")
    out_path = os.path.join(root, "src", "esp32", "web_assets.h")

    if not os.path.isdir(web_dir):
        raise SystemExit("web/ not found under %s" % root)

    files = _collect_files(web_dir)
    if not files:
        raise SystemExit("no files to embed under %s" % web_dir)

    _write_if_changed(out_path, _build_header(files))

    total_raw = sum(item["raw_size"] for item in files)
    total_gz = sum(len(item["gz"]) for item in files)
    for item in files:
        print("embed_web: %-32s %7d -> %7d bytes" %
              (item["path"], item["raw_size"], len(item["gz"])))
    print("embed_web: %d files, %d raw bytes, %d gzipped bytes" %
          (len(files), total_raw, total_gz))
    print("embed_web: wrote %s" % out_path)
    return out_path


if __name__ == "__main__":
    main()
else:
    _env = _scons_env()
    if _env is not None:
        _generated = main()
        _env.Depends("$BUILD_DIR/${PROGNAME}.elf", _generated)
